"""Generate Android's startup vector from the existing logo's isolated glyphs.

Uses the same silhouettes, stroke paths and timeline as LogoWritingReveal.
Requires OpenCV (only for this asset-generation step).
"""
import json
import math
from pathlib import Path
import cv2
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / 'android/app/src/main/res'
GLYPHS = json.loads((ROOT / 'tool/branding/logo_ink_strokes.json').read_text())
ATLAS = cv2.imread(str(ROOT / 'assets/images/apna_pos_logo_ink_atlas.png'), cv2.IMREAD_UNCHANGED)


def outline(index, bounds):
    alpha = ATLAS[index // 3 * 512:(index // 3 + 1) * 512,
                  index % 3 * 512:(index % 3 + 1) * 512, 3]
    return mask_outline((alpha > 96).astype('uint8'), bounds)


def mask_outline(mask, bounds, minimum_area=2):
    x, y, width, height = bounds
    contours, _ = cv2.findContours(mask, cv2.RETR_LIST, cv2.CHAIN_APPROX_SIMPLE)
    result = []
    for contour in contours:
        if abs(cv2.contourArea(contour)) < minimum_area:
            continue
        points = cv2.approxPolyDP(contour, 0.65, True).reshape(-1, 2)
        result.append('M' + 'L'.join(f'{x + px * width / 512:.1f},{y + py * height / 512:.1f}' for px, py in points) + 'Z')
    return ''.join(result)


def receipt_layers():
    """Preserve the supplied emblem's blue border, white paper and navy print."""
    tile = ATLAS[1024:1536, 1024:1536]
    b, g, r = cv2.split(tile[:, :, :3].astype('int16'))
    neutral = ((tile[:, :, 3] > 96) & (np.minimum(np.minimum(b, g), r) > 145) &
               (np.maximum(np.maximum(b, g), r) - np.minimum(np.minimum(b, g), r) < 40))
    contours, _ = cv2.findContours(neutral.astype('uint8'), cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    paper = np.zeros((512, 512), dtype='uint8')
    cv2.drawContours(paper, [max(contours, key=cv2.contourArea)], -1, 1, cv2.FILLED)
    printed = ((paper > 0) & (b < 190) & (g < 100) & (r < 90)).astype('uint8')
    printed = cv2.morphologyEx(printed, cv2.MORPH_CLOSE, np.ones((3, 3), dtype='uint8'))
    return [
        ('receipt_outline', '#0758F5', outline(8, GLYPHS[8]['rect'])),
        ('receipt_paper', '#F7F9FE', mask_outline(paper, GLYPHS[8]['rect'], 20)),
        ('receipt_ink', '#06265C', mask_outline(printed, GLYPHS[8]['rect'], 20)),
    ]


def stroke_path(points):
    result = [f'M{points[0][0]},{points[0][1]}']
    for p in points[1:]:
        result.append((p[0] + ','.join(map(str, p[1:]))) if isinstance(p[0], str)
                      else f'L{p[0]},{p[1]}')
    return ''.join(result)


def stroke_length(points):
    """Approximate each contour's length to match Flutter PathMetric pacing."""
    current = tuple(points[0])
    total = 0.0
    for segment in points[1:]:
        if isinstance(segment[0], str):
            start = current
            previous = current
            for sample in range(1, 101):
                t = sample / 100
                s = 1 - t
                if segment[0] == 'C':
                    x = s**3*start[0] + 3*s*s*t*segment[1] + 3*s*t*t*segment[3] + t**3*segment[5]
                    y = s**3*start[1] + 3*s*s*t*segment[2] + 3*s*t*t*segment[4] + t**3*segment[6]
                else:
                    x = s*s*start[0] + 2*s*t*segment[1] + t*t*segment[3]
                    y = s*s*start[1] + 2*s*t*segment[2] + t*t*segment[4]
                current = (x, y)
                total += math.dist(previous, current)
                previous = current
        else:
            total += math.dist(current, segment)
            current = tuple(segment)
    return total


wordmark_boxes = []
for index, glyph in enumerate(GLYPHS[:7]):
    alpha = ATLAS[index // 3 * 512:(index // 3 + 1) * 512,
                  index % 3 * 512:(index % 3 + 1) * 512, 3]
    x, y, width, height = cv2.boundingRect((alpha > 96).astype('uint8'))
    gx, gy, gw, gh = glyph['rect']
    wordmark_boxes.append((gx + x * gw / 512, gy + y * gh / 512,
                          gx + (x + width) * gw / 512, gy + (y + height) * gh / 512))
center_x = (min(b[0] for b in wordmark_boxes) + max(b[2] for b in wordmark_boxes)) / 2
center_y = (min(b[1] for b in wordmark_boxes) + max(b[3] for b in wordmark_boxes)) / 2

vector = [f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_android_startup_writing.py; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="288dp" android:height="288dp"
    android:viewportWidth="2400" android:viewportHeight="2400">
    <group android:name="brand_position" android:translateX="{1200 - center_x:.2f}" android:translateY="{1200 - center_y:.2f}">''']
targets = []
for index, glyph in enumerate(GLYPHS):
    if index == 8:
        # Android must draw the receipt too: Flutter may not be ready until the
        # native animation has finished. Derive its shapes from the same atlas.
        for name, color, path in receipt_layers():
            vector.append(f'<path android:name="{name}" android:pathData="{path}" '
                          f'android:fillColor="{color}" android:fillType="evenOdd" android:fillAlpha="0"/>')
            animation = f'startup_{name}'
            (RES / 'animator' / f'{animation}.xml').write_text('''<?xml version="1.0" encoding="utf-8"?>
<objectAnimator xmlns:android="http://schemas.android.com/apk/res/android"
    android:propertyName="fillAlpha" android:valueType="floatType"
    android:valueFrom="0" android:valueTo="1" android:startOffset="2680" android:duration="360"
    android:interpolator="@android:interpolator/fast_out_slow_in"/>
''')
            targets.append(f'<target android:name="{name}" android:animation="@animator/{animation}"/>')
        continue
    silhouette = outline(index, glyph['rect'])
    vector.append(f'<group><clip-path android:pathData="{silhouette}" android:fillType="evenOdd"/>')
    color = '#06265C' if index < 4 else '#0758F5'
    start = 100 + index * 320 if index < 7 else 2390
    duration = 360 if index < 7 else 350
    lengths = [stroke_length(points) for points in glyph['paths']]
    total_length = sum(lengths)
    elapsed = 0
    for segment, points in enumerate(glyph['paths']):
        name = f'ink_{index}_{segment}'
        vector.append(f'''<path android:name="{name}" android:pathData="{stroke_path(points)}"
            android:strokeColor="{color}" android:strokeWidth="{glyph['stroke']}"
            android:strokeLineCap="round" android:strokeLineJoin="round"
            android:trimPathEnd="{'0.04' if index == 0 and segment == 0 else '0'}"/>''')
        # Separate contours animate in writing order; Android trimPath only
        # trims a single contour, unlike Flutter's PathMetrics iterator.
        offset = start + round(duration * elapsed / total_length)
        segment_duration = max(1, round(duration * lengths[segment] / total_length))
        elapsed += lengths[segment]
        animation = f'startup_ink_{index}_{segment}'
        (RES / 'animator').mkdir(exist_ok=True)
        initial = '0.04' if index == 0 and segment == 0 else '0'
        (RES / 'animator' / f'{animation}.xml').write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<objectAnimator xmlns:android="http://schemas.android.com/apk/res/android"
    android:propertyName="trimPathEnd" android:valueType="floatType"
    android:valueFrom="{initial}" android:valueTo="1"
    android:startOffset="{offset}" android:duration="{segment_duration}"
    android:interpolator="@android:interpolator/linear"/>
''')
        targets.append(f'<target android:name="{name}" android:animation="@animator/{animation}"/>')
    # Settle the exact letter silhouette gradually, instead of leaving corners
    # missing until Android hands off to the completed Flutter glyph.
    fill_name = f'fill_{index}'
    vector.append(f'<path android:name="{fill_name}" android:pathData="{silhouette}" '
                  f'android:fillType="evenOdd" android:fillColor="{color}" android:fillAlpha="0"/>')
    fill_animation = f'startup_fill_{index}'
    (RES / 'animator' / f'{fill_animation}.xml').write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<objectAnimator xmlns:android="http://schemas.android.com/apk/res/android"
    android:propertyName="fillAlpha" android:valueType="floatType"
    android:valueFrom="0" android:valueTo="1"
    android:startOffset="{start + round(duration * 0.72)}" android:duration="{round(duration * 0.28)}"
    android:interpolator="@android:interpolator/fast_out_slow_in"/>
''')
    targets.append(f'<target android:name="{fill_name}" android:animation="@animator/{fill_animation}"/>')
    vector.append('</group>')
vector.append('</group></vector>')
(RES / 'animator/startup_brand_position.xml').write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<set xmlns:android="http://schemas.android.com/apk/res/android">
    <objectAnimator android:propertyName="translateX" android:valueType="floatType"
        android:valueFrom="{1200 - center_x:.2f}" android:valueTo="573"
        android:startOffset="2390" android:duration="630"
        android:interpolator="@android:interpolator/fast_out_slow_in"/>
    <objectAnimator android:propertyName="translateY" android:valueType="floatType"
        android:valueFrom="{1200 - center_y:.2f}" android:valueTo="573"
        android:startOffset="2390" android:duration="630"
        android:interpolator="@android:interpolator/fast_out_slow_in"/>
</set>
''')
targets.append('<target android:name="brand_position" android:animation="@animator/startup_brand_position"/>')
(RES / 'drawable/startup_ink.xml').write_text('\n'.join(vector))
(RES / 'drawable/startup_writing.xml').write_text('''<?xml version="1.0" encoding="utf-8"?>
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:drawable="@drawable/startup_ink">
''' + '\n'.join(targets) + '\n</animated-vector>\n')
print('Generated Android startup handwriting including the complete receipt emblem.')
